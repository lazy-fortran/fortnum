#!/usr/bin/env bash
# Register-tile kernels of fortnum's GEMM, emitted by fortgen in assembly.
# The shapes are the fastest measured on Zen 3, Broadwell, Zen 5 and Apple M3
# (fortgen docs/backends.md).
#
# Usage: gen_blas_tiles.sh FORTGEN_TILE [OUTPUT_DIR]
# FORTGEN_TILE is the fortgen-tile program of fortgen at FORTGEN_REVISION.
set -euo pipefail
FORTGEN_REVISION=86fdec7deae8c0596a23f60f95243bd0bccbf369
tile=$1
out=${2:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../../src/generated" && pwd)}
emit() {
    local name=$1 isa=$2 mr=$3 nr=$4 tmp
    tmp=$(mktemp)
    "$tile" "$isa" "$mr" "$nr" 4 0 "$name" "$tmp"
    {
        echo "/* Generated by tools/codegen/gen_blas_tiles.sh with fortgen $FORTGEN_REVISION; do not edit. */"
        cat "$tmp"
    } > "$out/$name.c"
    rm -f "$tmp"
}
emit fortnum_dtile_avx2_8x6 x86_64_avx2_fma 8 6
emit fortnum_dtile_avx512_24x8 x86_64_avx512 24 8
emit fortnum_dtile_neon_8x6 aarch64_neon 8 6

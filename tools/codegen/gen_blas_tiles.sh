#!/usr/bin/env bash
# Register-tile kernels of fortnum's GEMM, emitted by fortgen in assembly.
# The shapes are the fastest measured on Zen 3, Broadwell, Zen 5, Apple M3 and,
# for WebAssembly, in JavaScriptCore and V8
# (fortgen docs/backends.md).
#
# Usage: gen_blas_tiles.sh FORTGEN_TILE [OUTPUT_DIR]
# FORTGEN_TILE is the fortgen-tile program of fortgen at FORTGEN_REVISION.
set -euo pipefail
FORTGEN_REVISION=4b4adb510a038d3db0015f61f9a9bf743a583e92
tile=$1
out=${2:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../../src/generated" && pwd)}
emit() {
    local name=$1 isa=$2 mr=$3 nr=$4 mode=${5:-} unroll=${6:-4} tmp
    tmp=$(mktemp)
    "$tile" "$isa" "$mr" "$nr" "$unroll" 0 "$name" "$tmp" $mode
    {
        echo "/* Generated by tools/codegen/gen_blas_tiles.sh with fortgen $FORTGEN_REVISION; do not edit. */"
        cat "$tmp"
    } > "$out/$name.c"
    rm -f "$tmp"
}
emit fortnum_dtile_avx2_8x6 x86_64_avx2_fma 8 6
emit fortnum_dtile_avx512_24x8 x86_64_avx512 24 8
emit fortnum_dtile_neon_8x6 aarch64_neon 8 6
# the same tiles adding to C in place, for full tiles
emit fortnum_dtile_avx2_8x6_c x86_64_avx2_fma 8 6 update_c
emit fortnum_dtile_avx512_24x8_c x86_64_avx512 24 8 update_c
emit fortnum_dtile_neon_8x6_c aarch64_neon 8 6 update_c
# A read unpacked with its leading dimension, for thin products: added to C
# in place for full tiles, to a tile buffer for partial column panels
emit fortnum_dtile_avx2_8x6_sc x86_64_avx2_fma 8 6 update_c,a_strided
emit fortnum_dtile_avx512_24x8_sc x86_64_avx512 24 8 update_c,a_strided
emit fortnum_dtile_neon_8x6_sc aarch64_neon 8 6 update_c,a_strided
emit fortnum_dtile_avx2_8x6_sa x86_64_avx2_fma 8 6 a_strided
emit fortnum_dtile_avx512_24x8_sa x86_64_avx512 24 8 a_strided
emit fortnum_dtile_neon_8x6_sa aarch64_neon 8 6 a_strided
# B read unpacked with its leading dimension, for products with few rows
emit fortnum_dtile_avx2_8x6_bc x86_64_avx2_fma 8 6 update_c,b_strided
emit fortnum_dtile_avx512_24x8_bc x86_64_avx512 24 8 update_c,b_strided
emit fortnum_dtile_neon_8x6_bc aarch64_neon 8 6 update_c,b_strided
emit fortnum_dtile_avx2_8x6_ba x86_64_avx2_fma 8 6 b_strided
emit fortnum_dtile_avx512_24x8_ba x86_64_avx512 24 8 b_strided
emit fortnum_dtile_neon_8x6_ba aarch64_neon 8 6 b_strided
# the kernel of the packed TRSM: C - A B^T solved by a lower triangle with
# inverted diagonal in the registers, stored to C and transposed to the panel
emit fortnum_dtrsm_avx2_8x6 x86_64_avx2_fma 8 6 trsm
# the matrix coprocessor of Apple M1 to M3 (it cannot read B unpacked)
emit fortnum_dtile_amx_32x16 aarch64_amx 32 16 "" 2
emit fortnum_dtile_amx_32x16_c aarch64_amx 32 16 update_c 2
emit fortnum_dtile_amx_32x16_sc aarch64_amx 32 16 update_c,a_strided 2
emit fortnum_dtile_amx_32x16_sa aarch64_amx 32 16 a_strided 2
# WebAssembly SIMD128 for browsers, including Safari on the iPad
emit fortnum_dtile_wasm_8x4 wasm32_simd128 8 4
emit fortnum_dtile_wasm_8x4_c wasm32_simd128 8 4 update_c
emit fortnum_dtile_wasm_8x4_sc wasm32_simd128 8 4 update_c,a_strided
emit fortnum_dtile_wasm_8x4_sa wasm32_simd128 8 4 a_strided
emit fortnum_dtile_wasm_8x4_bc wasm32_simd128 8 4 update_c,b_strided
emit fortnum_dtile_wasm_8x4_ba wasm32_simd128 8 4 b_strided

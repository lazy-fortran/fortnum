program gen_bdf2
    use fortsym_expr, only: expr_t, sym, operator(+), operator(-), &
        operator(*), operator(/), operator(**)
    use fortsym_string, only: str_t, str, chars
    use fortsym_kernel, only: kernel_spec_t, emit_kernel, KERNEL_SUBROUTINE
    use fortnum_codegen_provenance, only: fortsym_revision, generated_path, &
        cost_block_text, insert_cost_block
    implicit none

    type(expr_t) :: h, ratio, y, previous, derivative, prediction, candidate, factor
    integer :: unit

    h = sym('h'); ratio = sym('ratio')
    y = sym('y'); previous = sym('previous')
    derivative = sym('derivative'); prediction = sym('prediction')
    candidate = sym('candidate'); factor = sym('factor')
    open (newunit=unit, file=generated_path('fortnum_bdf2_leaves.f90'), &
        status='replace', action='write')
    write (unit, '(a)') '! Generated by gen_bdf2; do not edit.'
    write (unit, '(a)') 'module fortnum_generated_bdf2'
    write (unit, '(a)') 'implicit none'
    write (unit, '(a)') 'private'
    write (unit, '(a)') 'public :: bdf2_weights, bdf_predict, bdf_error'
    write (unit, '(a)') 'contains'
    call emit('bdf2_weights', [str('h'), str('ratio')], &
        [str('alpha'), str('beta'), str('milne')], &
        [(1 + 2*ratio)/((1 + ratio)*h), &
        -ratio**2/((1 + ratio)*h), (1 + ratio)/(2 + 3*ratio)])
    ! Hermite extrapolation matches y(-k), y(0), y'(0); ratio=0 is Euler.
    call emit('bdf_predict', &
        [str('h'), str('ratio'), str('y'), str('previous'), str('derivative')], &
        [str('prediction')], &
        [y + h*derivative + ratio*(h*derivative - ratio*(y - previous))])
    call emit('bdf_error', [str('candidate'), str('prediction'), str('factor')], &
        [str('error')], [factor*(candidate - prediction)])
    write (unit, '(a)') 'end module fortnum_generated_bdf2'
    close (unit)

contains

    subroutine emit(name, arguments, outputs, roots)
        character(*), intent(in) :: name
        type(str_t), intent(in) :: arguments(:), outputs(:)
        type(expr_t), intent(in) :: roots(:)
        type(kernel_spec_t) :: spec
        character(:), allocatable :: code

        spec%name = str(name)
        spec%mode = KERNEL_SUBROUTINE
        spec%generator = str('gen_bdf2')
        spec%generator_revision = str(fortsym_revision())
        spec%regenerate_command = str('cd tools/codegen && fo exec gen_bdf2')
        spec%pure_procedure = .true.
        spec%elemental_procedure = .true.
        spec%args = arguments
        spec%outputs = outputs
        code = chars(emit_kernel(roots, spec))
        code = insert_cost_block(code, cost_block_text(roots, roots))
        write (unit, '(a)') code(:len(code) - 1)
    end subroutine emit
end program gen_bdf2

program gen_exprb
    use, intrinsic :: iso_fortran_env, only: real64
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, operator(-), &
        operator(*), operator(/), operator(**)
    use fortsym_string, only: str_t, str, chars
    use fortsym_kernel, only: kernel_spec_t, emit_kernel, KERNEL_SUBROUTINE
    use fortnum_codegen_provenance, only: fortsym_revision, generated_path, &
        cost_block_text, insert_cost_block
    implicit none

    type(arena_t), target :: arena
    type(expr_t) :: error
    integer :: unit

    call arena%init()
    error = sym(arena, 'error')
    open (newunit=unit, file=generated_path('fortnum_exprb_leaves.f90'), &
        status='replace', action='write')
    write (unit, '(a)') '! Generated by gen_exprb; do not edit.'
    write (unit, '(a)') 'module fortnum_generated_exprb'
    write (unit, '(a)') 'implicit none'
    write (unit, '(a)') 'private'
    write (unit, '(a)') 'public :: exprb_controller'
    write (unit, '(a)') 'contains'
    call emit('exprb_controller', [str('error')], [str('factor')], &
        [(4*error**(-1.0_real64/3))/5])
    write (unit, '(a)') 'end module fortnum_generated_exprb'
    close (unit)

contains

    subroutine emit(name, arguments, outputs, roots)
        character(*), intent(in) :: name
        type(str_t), intent(in) :: arguments(:), outputs(:)
        type(expr_t), intent(in) :: roots(:)
        type(kernel_spec_t) :: spec
        character(:), allocatable :: code

        spec%name = str(name)
        spec%mode = KERNEL_SUBROUTINE
        spec%generator = str('gen_exprb')
        spec%generator_revision = str(fortsym_revision())
        spec%regenerate_command = str('cd tools/codegen && fo exec gen_exprb')
        spec%pure_procedure = .true.
        spec%elemental_procedure = .true.
        spec%args = arguments
        spec%outputs = outputs
        code = chars(emit_kernel(roots, spec))
        code = insert_cost_block(code, cost_block_text(roots, roots))
        write (unit, '(a)') code(:len(code) - 1)
    end subroutine emit
end program gen_exprb

#!/usr/bin/env python3
"""Emit the Why3 theory of the exact derived DOP853 tableau.

The exact Q(sqrt 6) value of every coefficient is read from the comments of
the committed generated tableau src/generated/fortnum_dop853_tableau.f90, so
the proof obligations are about the coefficients fortnum actually rounds.

Usage: gen_dop853_model.py TABLEAU_F90 OUTPUT_MLW
"""

import re
import sys

STAGES = 12
BUSHY_ORDER = 8
E5_ORDER = 5
E3_ORDER = 3
ENTRY = re.compile(r"! (-?\d+(?:/\d+)?) \+ (-?\d+(?:/\d+)?)\*sqrt\(6\)")


def block(text, name, count):
    start = text.index(f":: {name}(")
    end = text.index("]", start)
    entries = ENTRY.findall(text[start:end])
    if len(entries) != count:
        raise SystemExit(f"{name}: expected {count} exact entries, got {len(entries)}")
    return entries


def literal(value):
    if "/" in value:
        numerator, denominator = value.split("/")
    else:
        numerator, denominator = value, "1"
    sign = "-" if numerator.startswith("-") else ""
    numerator = numerator.lstrip("-")
    magnitude = f"({numerator}.0 / {denominator}.0)"
    return f"(0.0 - {magnitude})" if sign else magnitude


def element(entry):
    rational, irrational = entry
    if irrational == "0":
        return literal(rational)
    return f"{literal(rational)} + {literal(irrational)} * r6"


def weighted_moment(weight, power):
    terms = []
    for i in range(1, STAGES + 1):
        factors = [f"{weight}{i}"] + [f"c{i}"] * power
        terms.append(" * ".join(factors))
    return "\n      + ".join(terms)


def main():
    text = open(sys.argv[1], encoding="utf-8").read()
    c = block(text, "dop853_c", STAGES)
    b = block(text, "dop853_b", STAGES)
    a = block(text, "dop853_a", STAGES * STAGES)
    e5 = block(text, "dop853_e5", STAGES)
    e3 = block(text, "dop853_e3", STAGES)

    out = [
        "(* Generated by why3/gen_dop853_model.py from",
        "   src/generated/fortnum_dop853_tableau.f90. Do not edit. *)",
        "",
        "theory DOP853_Exact_Tableau",
        "",
        "  use real.Real",
        "",
        "  (* r6 is a square root of 6; every goal holds for either sign, so",
        "     each is an identity in Q(sqrt 6), not a floating-point claim. *)",
        "  constant r6 : real",
        "  axiom r6_square : r6 * r6 = 6.0",
        "",
    ]
    for name, values in (("c", c), ("b", b), ("e5_", e5), ("e3_", e3)):
        for i, entry in enumerate(values, start=1):
            out.append(f"  constant {name}{i} : real = {element(entry)}")
        out.append("")
    for i in range(1, STAGES + 1):
        for j in range(1, STAGES + 1):
            value = element(a[(i - 1) * STAGES + j - 1])
            out.append(f"  constant a{i}_{j} : real = {value}")
    out.append("")

    for i in range(1, STAGES + 1):
        upper = " /\\ ".join(f"a{i}_{j} = 0.0" for j in range(i, STAGES + 1))
        out.append(f"  goal explicit_row{i} : {upper}")
    out.append("")
    for i in range(1, STAGES + 1):
        lower = " + ".join(f"a{i}_{j}" for j in range(1, i)) or "0.0"
        out.append(f"  goal row_sum{i} : {lower} = c{i}")
    out.append("")
    for k in range(1, BUSHY_ORDER + 1):
        out.append(f"  goal weight_moment{k} :\n      {weighted_moment('b', k - 1)}\n"
                   f"      = 1.0 / {k}.0")
    for k in range(1, E5_ORDER + 1):
        out.append(f"  goal e5_moment{k} :\n      {weighted_moment('e5_', k - 1)}\n"
                   "      = 0.0")
    for k in range(1, E3_ORDER + 1):
        out.append(f"  goal e3_moment{k} :\n      {weighted_moment('e3_', k - 1)}\n"
                   "      = 0.0")
    out += ["", "end", ""]
    open(sys.argv[2], "w", encoding="utf-8").write("\n".join(out))


if __name__ == "__main__":
    main()
